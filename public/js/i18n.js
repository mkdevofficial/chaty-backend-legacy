export function setLanguage(lang, { cache = true } = {}) {
  if (!translations[lang]) lang = 'ar';
  state.lang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  if (cache) {
    try {
      const prefs = JSON.parse(localStorage.getItem('chaty_prefs') || '{}');
      prefs.lang = lang;
      localStorage.setItem('chaty_prefs', JSON.stringify(prefs));
    } catch {
      /* ignore storage errors */
    }
  }
  document.dispatchEvent(new CustomEvent('chaty:language', { detail: { lang } }));
}

export function t(key, vars = {}) {
  const dict = translations[state.lang] || translations.ar;
  let value = dict[key] ?? translations.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    value = value.replaceAll(`{${k}}`, String(v));
  }
  return value;
}

export function errorText(error) {
  if (!error) return t('errors.generic');
  if (error.code) {
    const key = `errors.${error.code}`;
    const dict = translations[state.lang] || translations.ar;
    if (dict[key] || translations.en[key]) return t(key);
  }
  return error.message || t('errors.generic');
}

export function getLocale() {
  return state.lang === 'ar' ? 'ar-EG' : 'en-US';
}

export function isRTL() {
  return state.lang === 'ar';
}
